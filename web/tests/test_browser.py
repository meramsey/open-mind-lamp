"""Actual Chromium + Firefox desktop/mobile-viewport integration, mocked device HTTP.

This verifies browser behavior, not the ESP32 HTTP implementation or Android OS Wi-Fi.
"""
import functools
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
import json
from pathlib import Path
import threading
import unittest
import subprocess
import copy
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
TOKEN = 'a' * 64
SETTINGS = dict(brightness=.08, saturation=.9, sensitivity=.2, smoothing_ms=1500,
                starting_hue=180, sample_hz=20, accumulation_ms=1000, frame_hz=30,
                pixel=0, mode=1, enabled=True, rgb_order=False,
                gain_red=1, gain_green=1, gain_blue=1, channel_order_confirmed=False)


def calibration_state():
    return dict(active=False, ready=False, presented=False, phase='idle', run_id=0, step=0,
                index=0, expected='none', candidate_order='GRB', saved_order='GRB',
                saved_order_confirmed=False, remaining_ms=60000, brightness=.02)


def device_state(color):
    return dict(version='0.2.0', source='esp32s3-hwrng-rf-no-sleep', uptime_s=10,
                free_heap=100000, min_heap=99000, hue=73, target_hue=82,
                rng_words=200, rng_ones=3200, missed_slots=0, rng_failed=False, led_ok=True,
                color=copy.deepcopy(color), calibration=calibration_state(),
                network=dict(ap_ssid='OpenMindLamp-test', ap_ip='192.168.4.1',
                             station_ip='', hostname='openmindlamp-test', connected=False, rf_entropy_ready=True),
                session=dict(active=False, available=False, storage_ready=True, io_failed=False,
                             id='', reason='none', count=0, planned=0))


class BrowserTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        fixture = ROOT.parent / '.tools/host-tests/color_fixture'
        if not fixture.exists():
            subprocess.run([str(ROOT.parent / 'tools/test.sh')], check=True)
        else:
            subprocess.run(['cmake', '--build', str(fixture.parent), '--target', 'color_fixture'], check=True)
        # Generated by the exact production color-frame builder and API serializer.
        cls.frames = json.loads(subprocess.check_output([str(fixture)], text=True))
        cls.server = ThreadingHTTPServer(('127.0.0.1', 0), functools.partial(SimpleHTTPRequestHandler, directory=str(ROOT)))
        cls.thread = threading.Thread(target=cls.server.serve_forever, daemon=True); cls.thread.start()
        cls.url = f'http://127.0.0.1:{cls.server.server_port}'

    @classmethod
    def tearDownClass(cls):
        cls.server.shutdown(); cls.server.server_close(); cls.thread.join()

    def test_offline_browser_workflows(self):
        with sync_playwright() as p:
            for engine in (p.chromium, p.firefox):
                for width in (390, 1280):
                    with self.subTest(browser=engine.name, width=width):
                        browser = engine.launch()
                        page = browser.new_page(viewport=dict(width=width, height=1000), accept_downloads=True)
                        errors, external, writes = [], [], []
                        page.on('pageerror', lambda error: errors.append(str(error)))
                        page.on('request', lambda req: external.append(req.url) if not req.url.startswith(self.url) else None)
                        settings = dict(SETTINGS)
                        session = dict(active=False, available=False, storage_ready=True, io_failed=False,
                                       id='', reason='none', count=0, planned=0)
                        state = device_state(self.frames[5]); state['session'] = session

                        def route_api(route):
                            request = route.request
                            if request.headers.get('authorization') != f'Bearer {TOKEN}':
                                return route.fulfill(status=401, json=dict(error='Invalid token'))
                            path = request.url.split('/api/')[1]
                            if request.method == 'GET':
                                if path == 'status': return route.fulfill(json=state)
                                if path == 'settings': return route.fulfill(json=settings)
                                if path == 'export': return route.fulfill(body='{"type":"header","schema":1}\n', content_type='application/x-ndjson')
                            data = request.post_data_json; writes.append((path, data))
                            if path == 'settings': settings.update(data)
                            if path == 'session/start': session.update(active=True, available=True, id='test-session', reason='running', planned=data['samples'])
                            if path == 'session/stop': session.update(active=False, reason='user_stopped')
                            if path == 'session/clear': session.update(available=False, reason='none')
                            route.fulfill(json=dict(ok=True))

                        page.route('**/api/**', route_api)
                        page.goto(self.url)
                        page.locator('#token').fill(TOKEN)
                        page.locator('#auth button').click()
                        expect(page.locator('#login')).to_be_hidden()
                        expect(page.locator('#hue')).to_have_text('180.0')
                        self.assertLessEqual(page.evaluate('document.documentElement.scrollWidth'), width)
                        page.locator('#theme').click()
                        expect(page.locator('body')).to_have_class('light')
                        page.locator('[name=sensitivity]').fill('0.4')
                        page.locator('#controls button').click()
                        expect(page.locator('#notice')).to_contain_text('Settings saved')
                        self.assertEqual(settings['sensitivity'], .4)
                        self.assertIs(settings['enabled'], True)
                        page.locator('[name=protocol]').fill('Predeclared protocol 1')
                        page.locator('#trial button').click()
                        expect(page.locator('#controls button')).to_be_disabled()
                        expect(page.locator('#session')).to_contain_text('running')
                        page.locator('#stop').click()
                        expect(page.locator('#export')).to_be_enabled()
                        with page.expect_download() as download:
                            page.locator('#export').click()
                        self.assertIn('test-session', download.value.suggested_filename)
                        page.on('dialog', lambda dialog: dialog.accept())
                        page.locator('#clear').click()
                        expect(page.locator('#trial button')).to_be_enabled()
                        page.locator('#logout').click()
                        expect(page.locator('#login')).to_be_visible()
                        self.assertEqual(errors, [])
                        self.assertEqual(external, [])
                        self.assertTrue(any(path == 'session/start' and isinstance(data['samples'], int) for path, data in writes))
                        browser.close()

    def test_production_color_json_matches_browser_and_animated_snapshots(self):
        with sync_playwright() as p:
            for engine, width in ((p.chromium, 390), (p.firefox, 1280)):
                with self.subTest(browser=engine.name, width=width):
                    browser = engine.launch(); page = browser.new_page(viewport=dict(width=width, height=1000))
                    state = device_state(self.frames[0]); errors = []
                    page.on('pageerror', lambda e: errors.append(str(e)))

                    def route_api(route):
                        path = route.request.url.split('/api/')[1]
                        if path == 'status': return route.fulfill(json=state)
                        if path == 'settings' and route.request.method == 'GET': return route.fulfill(json=SETTINGS)
                        route.fulfill(json=dict(ok=True))

                    page.route('**/api/**', route_api); page.goto(self.url)
                    page.locator('#token').fill(TOKEN); page.locator('#auth button').click()
                    expect(page.locator('#login')).to_be_hidden()
                    for frame in self.frames:
                        state['color'] = copy.deepcopy(frame)
                        # User-triggered refresh; background interval stays at 1500 ms.
                        page.locator('#controls button').click()
                        expect(page.locator('#notice')).to_contain_text('Settings saved')
                        if frame['valid']:
                            expected = 'rgb(' + ', '.join(str(c) for c in frame['commanded_rgb']) + ')'
                            expect(page.locator('#orb')).to_have_css('background-color', expected)
                        else:
                            expect(page.locator('#orb')).to_have_css('background-color', 'rgba(0, 0, 0, 0)')
                            expect(page.locator('#color-age')).to_contain_text('Output unknown')
                        expect(page.locator('#hue')).to_have_text(f"{frame['logical_hue']:.1f}")
                        expect(page.locator('#rgb-command')).to_contain_text(', '.join(str(c) for c in frame['commanded_rgb']))
                    self.assertEqual(errors, []); browser.close()

    def test_user_observed_calibration_requires_seven_confirmations_before_save(self):
        with sync_playwright() as p:
            for engine in (p.chromium, p.firefox):
                with self.subTest(browser=engine.name):
                    browser = engine.launch(); page = browser.new_page(viewport=dict(width=390, height=1100))
                    state = device_state(self.frames[0]); settings = dict(SETTINGS); observations = []
                    sequence = ['red', 'green', 'blue', 'white', 'yellow', 'cyan', 'magenta']
                    c = state['calibration']

                    def route_api(route):
                        path = route.request.url.split('/api/')[1]
                        if route.request.method == 'GET':
                            return route.fulfill(json=state if path == 'status' else settings)
                        data = route.request.post_data_json
                        if path == 'calibration/start':
                            c.update(active=True, phase='identify', expected='red', index=0, run_id=c['run_id']+1, step=0, presented=True)
                        elif path == 'calibration/observe':
                            self.assertEqual(data['step'], c['step']); self.assertEqual(data['run_id'], c['run_id'])
                            observations.append(data['observed']); c['step'] += 1; c['index'] += 1
                            if c['phase'] == 'identify' and c['index'] == 3:
                                self.assertEqual(observations, ['green', 'red', 'blue'])
                                c.update(phase='verify', index=0, candidate_order='RGB')
                            if c['phase'] == 'verify' and c['index'] == 7:
                                c.update(phase='ready', ready=True, index=6)
                            c['expected'] = sequence[c['index']]
                        elif path == 'calibration/save':
                            self.assertEqual(observations[3:], sequence)
                            self.assertTrue(c['ready'])
                            settings.update(rgb_order=True, channel_order_confirmed=True)
                            c.update(active=False, phase='saved', saved_order='RGB', saved_order_confirmed=True)
                        elif path == 'calibration/cancel':
                            c.update(active=False, ready=False, phase='cancelled')
                        route.fulfill(json=dict(ok=True))

                    page.route('**/api/**', route_api); page.goto(self.url)
                    page.locator('#token').fill(TOKEN); page.locator('#auth button').click()
                    expect(page.locator('#login')).to_be_hidden()
                    page.locator('#calibration-start').click()
                    expect(page.locator('#controls button')).to_be_disabled()
                    expect(page.locator('#trial button')).to_be_disabled()
                    for seen in ['green', 'red', 'blue']:
                        page.locator('#calibration-seen').select_option(seen)
                        page.locator('#calibration-report').click()
                        expect(page.locator('#calibration-report')).to_be_enabled()
                    expect(page.locator('#calibration-state')).to_contain_text('proposed RGB')
                    self.assertFalse(settings['rgb_order']); self.assertFalse(settings['channel_order_confirmed'])
                    for expected in sequence:
                        expect(page.locator('#calibration-expected')).to_have_text(expected)
                        page.locator('#calibration-match').click()
                    expect(page.locator('#calibration-save')).to_be_visible()
                    self.assertFalse(settings['rgb_order'])
                    page.locator('#calibration-save').click()
                    expect(page.locator('#calibration-state')).to_contain_text('user-confirmed')
                    self.assertTrue(settings['rgb_order']); self.assertTrue(settings['channel_order_confirmed'])
                    expect(page.locator('[name=rgb_order]')).to_be_checked()
                    page.locator('#calibration-start').click(); page.locator('#calibration-cancel').click()
                    expect(page.locator('#calibration-state')).to_contain_text('cancelled')
                    self.assertTrue(settings['rgb_order']); browser.close()

    def test_late_status_does_not_overwrite_a_new_command_or_logout(self):
        with sync_playwright() as p:
            browser = p.chromium.launch(); page = browser.new_page()
            state = device_state(self.frames[0]); held = []; status_count = 0; block = False

            def route_api(route):
                nonlocal status_count
                path = route.request.url.split('/api/')[1]
                if path == 'status':
                    status_count += 1
                    if block and not held:
                        held.append((route, copy.deepcopy(state))); return
                    return route.fulfill(json=state)
                if route.request.method == 'GET': return route.fulfill(json=SETTINGS)
                state['color'] = copy.deepcopy(self.frames[1]); route.fulfill(json=dict(ok=True))
                if held:
                    stale_route, stale_state = held[0]; stale_route.fulfill(json=stale_state)

            page.route('**/api/**', route_api); page.goto(self.url)
            page.locator('#token').fill(TOKEN); page.locator('#auth button').click()
            expect(page.locator('#login')).to_be_hidden()
            block = True; page.wait_for_timeout(1800)
            self.assertTrue(held)
            before = status_count; page.wait_for_timeout(1700)
            self.assertEqual(status_count, before)  # single in-flight status request
            page.locator('#controls button').click()
            expect(page.locator('#orb')).to_have_css('background-color', 'rgb(0, 5, 0)')
            held.clear(); page.wait_for_timeout(1800)
            self.assertTrue(held)
            page.locator('#logout').click(); expect(page.locator('#login')).to_be_visible()
            held[0][0].fulfill(json=held[0][1]); page.wait_for_timeout(200)
            expect(page.locator('#orb')).to_have_css('background-color', 'rgba(0, 0, 0, 0)')
            expect(page.locator('#login')).to_be_visible()
            browser.close()


if __name__ == '__main__': unittest.main()
